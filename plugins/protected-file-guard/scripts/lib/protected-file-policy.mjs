function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

function fileNamePattern(names) {
  return new RegExp(
    `(?:^|/)(?:${names.map(escapeRegExp).join("|")})$`,
    "iu",
  );
}

